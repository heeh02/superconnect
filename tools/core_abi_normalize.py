"""Normalize, materialize, and identify canonical Core ABI manifests."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from core_abi_extract import generate_manifest
from core_abi_model import (
    DEFAULT_CONFIG,
    DEFAULT_IDENTITY_HEADER,
    DEFAULT_INCLUDE_DIR,
    DEFAULT_SURFACE_ROOT,
    DEFAULT_SYMBOL_BASELINE,
    canonical_bytes,
    fail,
    identity_hex,
    load_config,
    load_json,
    target_config,
)


def abi_surface(document: dict[str, Any]) -> dict[str, Any]:
    if set(document) != {
        "enums",
        "schemaVersion",
        "structs",
        "symbols",
        "target",
        "typedefs",
        "variant",
    }:
        fail("complete ABI manifest has unexpected fields")
    if document["schemaVersion"] != 1 or document["variant"] != "full":
        fail("ABI surfaces must be derived from a full schema-v1 manifest")
    return {
        "enums": document["enums"],
        "schemaVersion": 1,
        "structs": document["structs"],
        "symbols": document["symbols"],
        "typedefs": document["typedefs"],
    }


def resolve_manifest(
    surface: dict[str, Any],
    *,
    target: str,
    variant: str,
    config: dict[str, Any],
) -> dict[str, Any]:
    if (
        not isinstance(surface, dict)
        or set(surface) != {"enums", "schemaVersion", "structs", "symbols", "typedefs"}
        or surface["schemaVersion"] != 1
    ):
        fail("canonical ABI surface has unexpected fields")
    if variant not in config["variants"]:
        fail(f"unsupported Core ABI variant: {variant}")
    target_config(config, target)
    excluded = set(config["variants"][variant]["excludedSymbols"])
    symbols = surface["symbols"]
    if not isinstance(symbols, list):
        fail("canonical ABI surface symbols must be an array")
    names = {value.get("name") for value in symbols if isinstance(value, dict)}
    if not excluded <= names:
        fail(f"variant {variant} excludes symbols absent from the ABI surface")
    return {
        "enums": surface["enums"],
        "schemaVersion": 1,
        "structs": surface["structs"],
        "symbols": [value for value in symbols if value.get("name") not in excluded],
        "target": target,
        "typedefs": surface["typedefs"],
        "variant": variant,
    }


def materialize_manifest(
    *,
    target: str,
    variant: str,
    config_path: Path = DEFAULT_CONFIG,
    surface_root: Path = DEFAULT_SURFACE_ROOT,
) -> dict[str, Any]:
    config = load_config(config_path)
    target_entry = target_config(config, target)
    surface_path = Path(surface_root) / f"{target_entry['surface']}.json"
    surface = load_json(surface_path)
    raw = canonical_bytes(surface)
    try:
        existing = surface_path.read_bytes()
    except OSError as error:
        fail(f"cannot read canonical ABI surface {surface_path}: {error}")
    if existing != raw:
        fail(f"canonical ABI surface is not canonical JSON: {surface_path}")
    return resolve_manifest(surface, target=target, variant=variant, config=config)


def write_or_check(path: Path, raw: bytes, check: bool) -> None:
    if check:
        try:
            existing = path.read_bytes()
        except OSError as error:
            fail(f"generated ABI file is missing: {path}: {error}")
        if existing != raw:
            fail(f"generated ABI file is stale: {path}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_bytes(raw)
    temporary.replace(path)


def _macro_name(triple: str, variant: str) -> str:
    normalized = re.sub(r"[^A-Za-z0-9]", "_", triple).upper()
    return f"SC_CORE_ABI_ID_{normalized}_{variant.upper()}_V1"


def identity_header(
    config: dict[str, Any],
    identities: dict[tuple[str, str], str],
) -> bytes:
    lines = [
        "#pragma once",
        "",
        "/* Automatically generated by tools/core_abi_manifest.py. */",
        "/* Each value is the first 64 bits of one canonical manifest SHA-256. */",
        "",
        "#include <stdint.h>",
        "",
    ]
    first_condition = True
    for target in config["targets"]:
        triple = target["triple"]
        directive = "#if" if first_condition else "#elif"
        first_condition = False
        lines.append(f"{directive} {target['preprocessorCondition']}")
        lines.append("#define SC_CORE_ABI_IDENTITY_AVAILABLE_V1 1")
        for variant in ("full", "minimal"):
            lines.append(
                f"#define {_macro_name(triple, variant)} "
                f"UINT64_C(0x{identities[(triple, variant)]})"
            )
        lines.append(f"#define SC_CORE_CANONICAL_ABI_ID_FULL_V1 {_macro_name(triple, 'full')}")
        lines.append(
            f"#define SC_CORE_CANONICAL_ABI_ID_MINIMAL_V1 {_macro_name(triple, 'minimal')}"
        )
        lines.append("")
    lines.append("#endif")
    lines.append("")
    lines.extend(
        [
            "#ifndef SC_CORE_ABI_IDENTITY_AVAILABLE_V1",
            "#define SC_CORE_ABI_IDENTITY_AVAILABLE_V1 0",
            "#endif",
            "",
            "#if SC_CORE_ABI_IDENTITY_AVAILABLE_V1",
            "#if defined(SC_CORE_ABI_VARIANT_MINIMAL)",
            "#define SC_CORE_CANONICAL_ABI_ID_V1 SC_CORE_CANONICAL_ABI_ID_MINIMAL_V1",
            "#else",
            "#define SC_CORE_CANONICAL_ABI_ID_V1 SC_CORE_CANONICAL_ABI_ID_FULL_V1",
            "#endif",
            "#endif",
            "",
        ]
    )
    return "\n".join(lines).encode("utf-8")


def generate_set(
    *,
    surface_root: Path = DEFAULT_SURFACE_ROOT,
    identity_header_path: Path = DEFAULT_IDENTITY_HEADER,
    include_dir: Path = DEFAULT_INCLUDE_DIR,
    symbol_baseline: Path = DEFAULT_SYMBOL_BASELINE,
    config_path: Path = DEFAULT_CONFIG,
    clang: str = "clang",
    check: bool = False,
) -> dict[tuple[str, str], str]:
    config = load_config(config_path)
    surfaces: dict[str, bytes] = {}
    identities: dict[tuple[str, str], str] = {}
    for target in config["targets"]:
        triple = target["triple"]
        full_document = generate_manifest(
            target=triple,
            variant="full",
            include_dir=include_dir,
            symbol_baseline=symbol_baseline,
            config_path=config_path,
            clang=clang,
        )
        surface_name = target["surface"]
        surface_document = abi_surface(full_document)
        surface_raw = canonical_bytes(surface_document)
        if surface_name in surfaces and surfaces[surface_name] != surface_raw:
            fail(
                f"targets assigned to ABI surface {surface_name} do not have "
                "identical declarations/layouts"
            )
        surfaces[surface_name] = surface_raw
        for variant in ("full", "minimal"):
            document = resolve_manifest(
                surface_document,
                target=triple,
                variant=variant,
                config=config,
            )
            raw = canonical_bytes(document)
            identities[(triple, variant)] = identity_hex(raw)
    for surface_name, raw in surfaces.items():
        write_or_check(Path(surface_root) / f"{surface_name}.json", raw, check)
    write_or_check(Path(identity_header_path), identity_header(config, identities), check)
    return identities
